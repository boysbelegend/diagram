/**
 * Copy diagram code to clipboard
 * @param {string} code - The diagram code
 * @returns {Promise<boolean>} True if copied successfully
 */
export async function copyToClipboard(code) {
  try {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      await navigator.clipboard.writeText(code);
      return true;
    } else {
      // Fallback for older browsers
      const textarea = document.createElement('textarea');
      textarea.value = code;
      textarea.style.position = 'fixed';
      textarea.style.opacity = '0';
      document.body.appendChild(textarea);
      textarea.select();
      const success = document.execCommand('copy');
      document.body.removeChild(textarea);
      return success;
    }
  } catch (error) {
    console.error('Copy to clipboard failed:', error);
    return false;
  }
}

/**
 * Copy SVG to clipboard
 * @param {SVGElement} svgElement - The SVG element to copy
 * @returns {Promise<boolean>} True if copied successfully
 */
export async function copySVGToClipboard(svgElement) {
  try {
    const svgData = new XMLSerializer().serializeToString(svgElement);

    if (navigator.clipboard && navigator.clipboard.write) {
      const blob = new Blob([svgData], { type: 'image/svg+xml' });
      const item = new ClipboardItem({ 'image/svg+xml': blob });
      await navigator.clipboard.write([item]);
      return true;
    } else {
      // Fallback: copy as text
      return await copyToClipboard(svgData);
    }
  } catch (error) {
    console.error('Copy SVG to clipboard failed:', error);
    return false;
  }
}

/**
 * Share diagram (using Web Share API if available)
 * @param {string} code - The diagram code
 * @param {string} title - The diagram title
 * @returns {Promise<boolean>} True if shared successfully
 */
export async function shareDiagram(code, title = 'Mermaid Diagram') {
  if (!navigator.share) {
    console.warn('Web Share API not supported');
    return false;
  }

  try {
    await navigator.share({
      title: title,
      text: code,
      // Note: files can also be shared if needed
    });
    return true;
  } catch (error) {
    // User cancelled or error occurred
    console.error('Share failed:', error);
    return false;
  }
}

/**
 * Generate shareable URL (for Mermaid Live Editor)
 * @param {string} code - The diagram code
 * @returns {string} URL to Mermaid Live Editor
 */
export function generateShareableURL(code) {
  const encoded = btoa(encodeURIComponent(code));
  return `https://mermaid.live/edit#${encoded}`;
}

// Helper functions

/**
 * Download a blob as a file
 * @param {Blob} blob - The blob to download
 * @param {string} filename - The filename
 */
function downloadBlob(blob, filename) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.style.display = 'none';
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);

  // Clean up
  setTimeout(() => URL.revokeObjectURL(url), 100);
}

/**
 * Escape HTML special characters
 * @param {string} text - Text to escape
 * @returns {string} Escaped text
 */
function escapeHtml(text) {
  const div = document.createElement('div');
  div.textContent = text;
  return div.innerHTML;
}
