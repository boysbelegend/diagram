/**
 * Export diagram as PNG
 * @param {SVGElement} svgElement - The SVG element to export
 * @param {string} filename - The filename for the export
 * @returns {Promise<void>}
 */
export async function exportAsPNG(svgElement, filename = 'diagram.png') {
  return new Promise((resolve, reject) => {
    try {
      const canvas = document.createElement('canvas');
      const ctx = canvas.getContext('2d');

      // Get SVG dimensions
      const bbox = svgElement.getBBox();
      const width = bbox.width || svgElement.width.baseVal.value || 800;
      const height = bbox.height || svgElement.height.baseVal.value || 600;

      // Set canvas size with scale for better quality
      const scale = 2; // Higher resolution
      canvas.width = width * scale;
      canvas.height = height * scale;

      // Serialize SVG
      const svgData = new XMLSerializer().serializeToString(svgElement);
      const svgBlob = new Blob([svgData], { type: 'image/svg+xml;charset=utf-8' });
      const url = URL.createObjectURL(svgBlob);

      const img = new Image();

      img.onload = () => {
        // Fill white background
        ctx.fillStyle = 'white';
        ctx.fillRect(0, 0, canvas.width, canvas.height);

        // Draw image scaled
        ctx.drawImage(img, 0, 0, canvas.width, canvas.height);

        // Convert to blob and download
        canvas.toBlob((blob) => {
          downloadBlob(blob, filename);
          URL.revokeObjectURL(url);
          resolve();
        }, 'image/png');
      };

      img.onerror = (error) => {
        URL.revokeObjectURL(url);
        reject(new Error('Failed to load SVG image'));
      };

      img.src = url;
    } catch (error) {
      reject(error);
    }
  });
}

/**
 * Export diagram as SVG
 * @param {SVGElement} svgElement - The SVG element to export
 * @param {string} filename - The filename for the export
 */
export function exportAsSVG(svgElement, filename = 'diagram.svg') {
  const svgData = new XMLSerializer().serializeToString(svgElement);

  // Add XML declaration and make it standalone
  const svgBlob = new Blob(
    ['<?xml version="1.0" encoding="UTF-8"?>\n' + svgData],
    { type: 'image/svg+xml;charset=utf-8' }
  );

  downloadBlob(svgBlob, filename);
}

